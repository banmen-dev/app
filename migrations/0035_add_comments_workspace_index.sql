-- 組織のホームの「最近の更新」（recent-activity、#1262）が、ワークスペースのコメントを新しい順に引くための索引。
-- 広げる変更（一意でない索引を足すだけ）で、前の版のコードは使わないが、戻しても動く。
-- 今の索引 comments_task (task_id, created_at, id) はタスク1件の一覧用で、ワークスペースの全コメントを読んで並べ替えることになるため、
-- カーソルの並び（created_at, id の降順）に合わせて id まで並べる。消したコメントも持つ（消していない行だけの部分索引にすると、
-- 条件を問い合わせの文と同じ式にそろえる必要が出る。消した行は本文を空にして残すだけで、量は少ない）。
-- 行を書き換える文は無く、索引を作るだけ。

CREATE INDEX comments_workspace_created ON comments (workspace_id, created_at, id);
